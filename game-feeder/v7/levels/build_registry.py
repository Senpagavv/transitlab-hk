"""Collect the levels of v7 into levels/registry.js (run by v7/build.py; can be run on its own).

Two kinds of entries, one list (window.TL_LEVELS):
  built-in  levels/builtin.json — the levels written inside each mode's data.js: title, order, challenge, where on
            the Hong Kong map (for the hub). No level data here; the mode keeps it.
  files     levels/m1 … m4/*.json in the format «tl-level/1» (see levels/README.md): the level itself plus the same
            facts. A file with the key of a built-in level replaces it; a new key adds a level. Deleting the file
            removes it — nothing else to clean up.
A file that fails the checks is reported and left out; the build goes on.
"""
import json
import re
from pathlib import Path

HERE = Path(__file__).resolve().parent
KEY = re.compile(r'^[a-z0-9][a-z0-9-]*$')
# the fields each mode's level data must have (the rest have defaults in the mode's engine)
NEEDS = {1: ['cols', 'rows'], 2: ['cols', 'rows', 'origins', 'destinations', 'tiers'],
         3: ['cols', 'rows', 'origins', 'destinations', 'roads', 'tiers'], 4: ['cols', 'rows', 'origins', 'destinations', 'land', 'tiers']}


def problems(e):
    """What is wrong with one level file (empty list = fine)."""
    out = []
    if e.get('format') != 'tl-level/1':
        out.append('format must be "tl-level/1"')
    if e.get('mode') not in NEEDS:
        return out + ['mode must be 1, 2, 3 or 4']
    if not KEY.match(str(e.get('key', ''))):
        out.append('key: lower-case letters, digits and «-», e.g. "m3-2"')
    if not e.get('title'):
        out.append('title is missing')
    lv = e.get('level')
    if not isinstance(lv, dict):
        return out + ['level (the level data) is missing']
    out += [f'level.{f} is missing' for f in NEEDS[e['mode']] if f not in lv]
    t = lv.get('tiers')
    if t is not None and not (isinstance(t, list) and len(t) == 3 and t[0] <= t[1] <= t[2]):
        out.append('level.tiers must be [pass, high, master], rising')
    return out


def build():
    builtin = json.loads((HERE / 'builtin.json').read_text(encoding='utf8'))['levels']
    entries = {(b['mode'], b['key']): {**b, 'builtin': True} for b in builtin}
    seen, report = {}, []
    for f in sorted(HERE.glob('m[1-4]/*.json')):
        try:
            e = json.loads(f.read_text(encoding='utf8'))
        except json.JSONDecodeError as exc:
            report.append(f'✗ {f.relative_to(HERE)}: not valid JSON ({exc})')
            continue
        bad = problems(e)
        if not bad and f.parent.name != f"m{e['mode']}":
            bad.append(f"mode {e['mode']} but the file is in {f.parent.name}/")
        k = (e.get('mode'), e.get('key'))
        if not bad and k in seen:
            bad.append(f'key {e["key"]} is used by {seen[k]} too')
        if bad:
            report.append(f'✗ {f.relative_to(HERE)}: ' + '; '.join(bad))
            continue
        seen[k] = f.name
        replaced = k in entries
        entries[k] = {**{x: y for x, y in e.items() if x != 'format'}, 'file': f'{f.parent.name}/{f.name}'}
        report.append(f"{'↻' if replaced else '+'} {f.relative_to(HERE)} → mode {e['mode']} {e['key']}" + (' (replaces the built-in level)' if replaced else ''))
    items = sorted(entries.values(), key=lambda e: (e['mode'], e.get('order', 99), e['key']))
    js = ('// Generated by levels/build_registry.py — do not edit. Add a level: put a «tl-level/1» JSON file in levels/m1…m4/\n'
          '// and run python v7/build.py (see levels/README.md).\n'
          '(function(root){const list=' + json.dumps(items, ensure_ascii=False, separators=(',', ':')) + ';\n'
          '  root.TL_LEVELS={list,mode:n=>list.filter(l=>l.mode===n),get:(n,k)=>list.find(l=>l.mode===n&&l.key===k)||null};\n'
          "  if(typeof module!=='undefined')module.exports=root.TL_LEVELS;\n"
          "})(typeof window!=='undefined'?window:globalThis);\n")
    (HERE / 'registry.js').write_text(js, encoding='utf8')
    return items, report


if __name__ == '__main__' or __name__ == '<run_path>':
    items, report = build()
    for r in report:
        print('  ' + r)
    print(f'levels: {len(items)} ({sum(1 for i in items if not i.get("builtin") or i.get("file"))} from files) → levels/registry.js')
