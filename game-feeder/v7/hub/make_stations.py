"""Write hub/stations.js: MTR and Light Rail stations → [lon, lat], keyed by the Chinese name without 「站」 (and by the
English name), from data/web/places.json (read only). Levels say where they are with hub.station; the hub looks it up here."""
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[3]
places = json.loads((ROOT / 'data/web/places.json').read_text(encoding='utf8'))['places']
out = {}
for p in places:
    if p['kind'] not in ('mtr', 'light_rail'):
        continue
    ll = [round(p['lon'], 6), round(p['lat'], 6)]
    zh = p['name_zh'].split(',')[0].strip()
    zh = zh[:-1] if zh.endswith('站') else zh
    en = p['name_en'].split(',')[0].replace(' Station', '').strip()
    for k in (zh, en):
        if p['kind'] == 'mtr' or k not in out:      # an MTR station keeps its name over a Light Rail stop of the same name
            out[k] = ll
js = ('// Generated by hub/make_stations.py from data/web/places.json — MTR and Light Rail stations, [lon, lat].\n'
      'window.TL_STATIONS=' + json.dumps(out, ensure_ascii=False, separators=(',', ':')) + ';\n')
(Path(__file__).resolve().parent / 'stations.js').write_text(js, encoding='utf8')
print(len(out), 'names →', 'hub/stations.js')
