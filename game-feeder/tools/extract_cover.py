"""Pull only what the opening cover needs out of the team's product-suite HTML.

The suite (TransitLab-產品套件.html, by a teammate) inlines ~640 KB of DATA. The cover
uses the dot field, the land bitmap, the coastline, the 24-hour detector tide and zone
names for the hover card. This writes those (~85 KB) to v2/cover-data.js as window.COVER.

Usage: python tools/extract_cover.py "<path to TransitLab-產品套件.html>"
"""
import hashlib, json, re, sys
from pathlib import Path

src = Path(sys.argv[1])
raw = src.read_bytes()
html = raw.decode('utf8')
script = re.findall(r'<script[^>]*>(.*?)</script>', html, flags=re.S)[0]
start = script.index('var DATA=') + len('var DATA=')
D, _ = json.JSONDecoder().raw_decode(script[start:])

T = D['traffic']
# Mean speed per hour weighted by detector count — the same number the suite's cover shows.
speed = []
for h in range(24):
    wd = sum(r['det'] for r in T['roads'])
    speed.append(round(sum(r['speed'][h] * r['det'] for r in T['roads']) / wd, 2))

cover = {k: D[k] for k in ['W', 'H', 'STEP', 'BORDER_STEP', 'cols', 'rows', 'dcols', 'coast', 'land', 'dotsI', 'dotsV', 'dotZ', 'baseMax', 'geom', 'distNames']}
cover['tide'] = {'factor24': T['factor24'], 'flow24': T['flow24'], 'speed24': speed, 'source': T.get('source'), 'period': T.get('period')}
cover['zones'] = [{'l': z['l'], 'di': z['di'], 'ti': z['ti']} for z in D['zoneMeta']]
cover['from'] = {'file': src.name, 'sha256': hashlib.sha256(raw).hexdigest()}

out = Path(__file__).resolve().parent.parent / 'v2' / 'cover-data.js'
body = json.dumps(cover, ensure_ascii=False, separators=(',', ':'))
out.write_text('// Generated by tools/extract_cover.py from the team product suite. Do not edit by hand.\n'
               'window.COVER=' + body + ';\n', encoding='utf8')
print(f'wrote {out} ({len(body) // 1024} KB) from {src.name} sha256 {cover["from"]["sha256"][:12]}')
